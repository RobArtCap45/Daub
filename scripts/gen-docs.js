// Generate docs/node-reference.md from the node definitions in app/src/engine.js.
// Usage: npm run docs     (CI fails if the committed file is out of date)
const fs = require('fs');
const path = require('path');

global.window = global;
require('../app/src/engine.js');
require('../app/src/script.js');
const { NODES } = window.Loom;
const { reference } = window.Loom.script;

const TYPE = { num: 'number or list', geo: 'shapes', pts: 'points', any: 'any list', enum: 'choice', svg: 'SVG file', draw: 'drawn path' };
const OUT = { num: 'numbers', geo: 'shapes', pts: 'points', any: 'a list' };
const fmt = (v) => (v === null || v === undefined ? '' : typeof v === 'number' ? String(+v.toFixed(6)) : '`' + v + '`');
const sig = Object.fromEntries(reference({}).map((r) => [r.name, r.sig]));

const byCat = new Map();
Object.entries(NODES).forEach(([type, def]) => { if (!byCat.has(def.cat)) byCat.set(def.cat, []); byCat.get(def.cat).push([type, def]); });

const lines = [
  '# Node reference',
  '',
  '<!-- Generated by scripts/gen-docs.js from app/src/engine.js. Do not edit by hand: run `npm run docs`. -->',
  '',
  'Every node, grouped by the category you see in the add-node search. The code under each name is how to write it in the [Script language](script-language.md).',
  'Any number input also accepts a **list**; lists are matched up item by item (a single number is repeated to fit).',
  '',
];

for (const [cat, nodes] of byCat) {
  lines.push(`## ${cat}`, '');
  for (const [type, def] of nodes) {
    lines.push(`### ${def.label}`, '', '```', sig[type], '```', '', def.desc || '', '');
    const inputs = def.inputs;
    if (inputs.length) {
      lines.push('| Input | Kind | Default | Notes |', '| --- | --- | --- | --- |');
      for (const s of inputs) lines.push(`| \`${s.n}\` | ${TYPE[s.t] || s.t} | ${s.t === 'enum' ? '`' + s.d + '`' : fmt(s.d)} | ${s.t === 'enum' ? s.o.map((o) => '`' + o + '`').join(', ') : ''} |`);
      lines.push('');
    }
    lines.push(def.out ? `Gives: ${OUT[def.out] || def.out}.` : 'Gives: nothing (this node is the end of the graph).', '');
  }
}

fs.writeFileSync(path.join(__dirname, '..', 'docs', 'node-reference.md'), lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
console.log('wrote docs/node-reference.md (' + Object.keys(NODES).length + ' nodes)');
